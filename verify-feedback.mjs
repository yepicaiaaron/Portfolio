import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const intro=read('dist/js/pioneer-intro.js'),morph=read('dist/js/pioneer-morph.js'),booking=read('dist/js/booking.js'),narrative=read('dist/js/narrative.js');
assert(!/speechSynthesis|SpeechSynthesisUtterance|Narration off/.test(intro));
assert(!/Soul AI Lab|CC BY-SA/.test(intro));
assert(!morph.includes('assets/optimised/research.mp4'),'Licensed clip must not remain after its visible credit is removed');
assert(morph.includes('assets/optimised/audience-mobile.mp4'));
assert(!morph.includes("word('Build.')"));
assert(morph.includes('crystal-future.mp4')&&morph.includes('drawReveal')&&morph.includes('ctx.clip()'));
assert(morph.includes("aria-pressed")&&morph.includes('revealButton.onclick'));
assert(morph.includes('crystal.suspend()')&&morph.includes('research.suspend()'));
assert(booking.includes('calendar/appointments/schedules/')&&booking.includes('?gv=true'));
assert(booking.includes('dialog.showModal()')&&booking.includes("dialog.addEventListener('close'"));
assert(booking.includes('opener?.focus')&&booking.includes('replaceChildren()'));
assert(narrative.includes("id:'recognition'")&&narrative.includes("id:'clients'"));
assert(narrative.includes('Nominee · 2018'),'Do not turn a nomination into an award');
assert(narrative.includes('Expert on generative media'));
assert(intro.includes('Trusted by international brands and government'));
assert(!/Built at Yepic|Used by people at|published user \/ client wall|not a list of personal commissions/.test(intro+narrative));
assert(narrative.includes('I founded and led Yepic')&&narrative.includes('I led these projects'));
const selectedLogos=intro.match(/const trustedClients=(\[.*\]);/)[1];
const logos=JSON.parse(selectedLogos.replaceAll("'",'"'));
assert.equal(logos.length,10);assert.equal(new Set(logos.map(([name])=>name)).size,10);
for(const [,i] of logos)assert(fs.existsSync('dist/assets/optimised/yepic-client-'+i+'.webp'));
assert(fs.statSync('dist/assets/optimised/crystal-future.mp4').size<350000,'Keep the new clip below 350KB');
assert(fs.statSync('dist/assets/optimised/crystal-future.webp').size<50000);
for(const f of ['feedback.css'])assert(read('dist/index.html').includes(f+'?v='));
console.log('Feedback regressions: narration removed, licensed demo replaced, scoped crystal reveal, resource cleanup, booking lifecycle, recognition and media budgets passed.');
